# Numpy Array Creation & Slicing
from datetime import datetime

# Load date as strings, numeric columns as floats
data_pasadena = np.genfromtxt(
    '2013-2014-Pasadena-Temperature-Data.csv',
    delimiter=',',
    skip_header=1,
    dtype=str
)

dates_str = data_pasadena[:, 0]
# Convert string dates to datetime objects for clean plotting
dates = [datetime.strptime(d, '%Y-%m-%d') for d in dates_str]

high_temp = data_pasadena[:, 1].astype(float)
low_temp = data_pasadena[:, 2].astype(float)

"""### Graphing the Data

Plot x, y_1 and y_2 with the elements shown in the instructions on the HW page.
"""

# Graphing the Data
plt.figure(figsize=(10, 5))
plt.plot(dates, high_temp, color='red', label='High Temperature', alpha=0.8)
plt.plot(dates, low_temp, color='blue', label='Low Temperature', alpha=0.8)

# Shading between high and low
plt.fill_between(dates, high_temp, low_temp, color='blue', alpha=0.15)

plt.title('Daily High and Low Temperatures - Pasadena, CA (2013-2014)')
plt.xlabel('Date')
plt.ylabel('Temperature (°F)')
plt.grid(True, linestyle='--', alpha=0.5)
plt.legend(loc='upper right')
plt.gcf().autofmt_xdate()  # Rotates date tick labels cleanly
plt.tight_layout()
plt.show()

